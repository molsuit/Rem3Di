"""Write the vulture whitelist of pydantic fields and enum members.

Vulture cannot see that a pydantic field or an enum member is read through
yaml or serialization, so every one would be reported as an unused variable.
This scans the workspace sources, finds every class that derives (directly or
through other workspace classes) from ``pydantic.BaseModel`` or ``enum.Enum``,
and writes their field and member names to ``generated_whitelist.py`` (not
committed; regenerated on every run by ``run_vulture.py``).
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

WORKSPACE_ROOT = Path(__file__).resolve().parents[2]
SOURCE_ROOTS = ["packages", "preparers", "scripts", "tests"]
ROOT_BASES = {
    "BaseModel",
    "RootModel",
    "Enum",
    "IntEnum",
    "StrEnum",
    "Flag",
    "IntFlag",
}
OUTPUT = Path(__file__).resolve().parent / "generated_whitelist.py"


def _base_name(node: ast.expr) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Subscript):  # Generic[...] / RootModel[...]
        return _base_name(node.value)
    return None


def _source_files() -> list[Path]:
    files: list[Path] = []
    for root in SOURCE_ROOTS:
        files.extend(
            path
            for path in (WORKSPACE_ROOT / root).rglob("*.py")
            if ".venv" not in path.parts and "__pycache__" not in path.parts
        )
    return sorted(files)


def _classes(files: list[Path]) -> list[ast.ClassDef]:
    classes: list[ast.ClassDef] = []
    for path in files:
        try:
            tree = ast.parse(path.read_text(), filename=str(path))
        except SyntaxError as error:
            print(f"skipping {path}: {error}", file=sys.stderr)
            continue
        classes.extend(node for node in ast.walk(tree) if isinstance(node, ast.ClassDef))
    return classes


def _field_names(class_node: ast.ClassDef) -> set[str]:
    names: set[str] = set()
    for statement in class_node.body:
        if isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name):
            names.add(statement.target.id)
        elif isinstance(statement, ast.Assign):
            names.update(
                target.id for target in statement.targets if isinstance(target, ast.Name)
            )
    return names


def model_field_names(files: list[Path]) -> tuple[set[str], set[str]]:
    """Field and member names of every pydantic model and enum in ``files``, and the classes."""
    classes = _classes(files)
    bases_by_class: dict[str, set[str]] = {}
    for class_node in classes:
        bases = {name for base in class_node.bases if (name := _base_name(base))}
        bases_by_class.setdefault(class_node.name, set()).update(bases)

    # Transitive closure over workspace classes (matched by name).
    model_classes: set[str] = set()
    changed = True
    while changed:
        changed = False
        for name, bases in bases_by_class.items():
            if name not in model_classes and bases & (ROOT_BASES | model_classes):
                model_classes.add(name)
                changed = True

    fields: set[str] = set()
    for class_node in classes:
        if class_node.name in model_classes:
            fields |= _field_names(class_node)
    return fields, model_classes


def main() -> None:
    fields, model_classes = model_field_names(_source_files())
    lines = [
        "# Generated by tools/vulture/generate_whitelist.py; do not edit or commit.",
        "# Fields of pydantic models and members of enums, read through yaml and",
        "# serialization rather than by name.",
        "",
        *(f"_.{name}" for name in sorted(fields)),
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(fields)} field and member names from {len(model_classes)} classes")


if __name__ == "__main__":
    main()
