"""The bundle and dataset format (``BENCHMARK_DATA_FORMAT.md`` §4): what is on disk and what is valid.

A bundle is a table (``dataset.yaml``, ``table.parquet``, ``provenance.yaml``)
with one row per stereoisomer; a dataset is the same three files with its
structures beside them and one table row per structure. This subpackage owns
the schema (:mod:`spec`, :mod:`provenance`), identity assignment
(:mod:`identity`), the disk io of the three files and the table's content hash
(:mod:`table`), the split codes (:mod:`split_codes`) and the invariants
(:mod:`invariants`). :mod:`verify` re-checks a whole dataset directory; it reads
the structures through :mod:`remedi_data.dataset`, which itself reads the format,
so it is imported by its module path and not exported here. It is torch-free.
"""

